import {
  createCipheriv,
  createDecipheriv,
  createHash,
  randomBytes,
} from 'node:crypto';

/** A small seam for replacing local encryption with a KMS envelope cipher. */
export interface SecretCipher {
  encrypt(plaintext: string): string;
  decrypt(ciphertext: string): string;
}

export class SecretCipherConfigurationError extends Error {
  constructor(message = 'A 32-byte Feishu token encryption key is required') {
    super(message);
    this.name = 'SecretCipherConfigurationError';
  }
}

export class SecretCipherError extends Error {
  constructor(message = 'The encrypted Feishu credential is invalid') {
    super(message);
    this.name = 'SecretCipherError';
  }
}

/**
 * AES-256-GCM implementation used by the single-instance deployment. The
 * serialized value contains no plaintext and is versioned so a KMS-backed
 * implementation can be introduced without changing the repository schema.
 */
export class Aes256GcmSecretCipher implements SecretCipher {
  readonly #key: Buffer;

  constructor(key: Buffer | string) {
    this.#key = normalizeKey(key);
  }

  static fromEnvironment(value: string | undefined): Aes256GcmSecretCipher {
    if (!value || !value.trim()) throw new SecretCipherConfigurationError();
    return new Aes256GcmSecretCipher(value);
  }

  encrypt(plaintext: string): string {
    if (typeof plaintext !== 'string' || plaintext.length === 0) {
      throw new SecretCipherError('The Feishu credential cannot be empty');
    }
    const iv = randomBytes(12);
    const cipher = createCipheriv('aes-256-gcm', this.#key, iv);
    const ciphertext = Buffer.concat([
      cipher.update(plaintext, 'utf8'),
      cipher.final(),
    ]);
    const tag = cipher.getAuthTag();
    return [
      'v1',
      iv.toString('base64url'),
      tag.toString('base64url'),
      ciphertext.toString('base64url'),
    ].join('.');
  }

  decrypt(serialized: string): string {
    try {
      const parts = serialized.split('.');
      if (parts.length !== 4) throw new Error('unsupported ciphertext');
      const [version, ivPart, tagPart, ciphertextPart] = parts;
      if (version !== 'v1' || !ivPart || !tagPart || !ciphertextPart) {
        throw new Error('unsupported ciphertext');
      }
      const iv = Buffer.from(ivPart, 'base64url');
      const tag = Buffer.from(tagPart, 'base64url');
      const ciphertext = Buffer.from(ciphertextPart, 'base64url');
      if (iv.length !== 12 || tag.length !== 16 || ciphertext.length === 0) {
        throw new Error('invalid ciphertext');
      }
      const decipher = createDecipheriv('aes-256-gcm', this.#key, iv);
      decipher.setAuthTag(tag);
      return Buffer.concat([
        decipher.update(ciphertext),
        decipher.final(),
      ]).toString('utf8');
    } catch {
      throw new SecretCipherError();
    }
  }
}

function normalizeKey(value: Buffer | string): Buffer {
  if (Buffer.isBuffer(value)) {
    if (value.length !== 32) throw new SecretCipherConfigurationError();
    return Buffer.from(value);
  }
  const text = value.trim();
  if (!text) throw new SecretCipherConfigurationError();
  if (/^[a-f0-9]{64}$/iu.test(text)) {
    return Buffer.from(text, 'hex');
  }
  // Prefer base64url/base64 when it decodes to exactly 32 bytes. This allows
  // secrets generated by common Secret Manager CLIs without imposing one
  // textual representation.
  try {
    const canonical = text
      .replace(/\+/gu, '-')
      .replace(/\//gu, '_')
      .replace(/=+$/u, '');
    const decoded = Buffer.from(canonical, 'base64url');
    if (decoded.length === 32 && decoded.toString('base64url') === canonical) {
      return decoded;
    }
  } catch {
    // Fall through to the explicit raw UTF-8 check below.
  }
  const raw = Buffer.from(text, 'utf8');
  if (raw.length === 32) return raw;
  throw new SecretCipherConfigurationError();
}

/** Stable digest helper for tests and diagnostics without exposing state. */
export function digestSecret(value: string): string {
  return createHash('sha256').update(value, 'utf8').digest('hex');
}
